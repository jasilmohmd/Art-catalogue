import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artworksDirectory = path.join(projectRoot, "public", "artworks");
const outputFile = path.join(projectRoot, "data", "artworks.ts");
const supportedExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

export function parseArtworkFilename(fileName) {
  const extension = path.extname(fileName).toLowerCase();

  if (!supportedExtensions.has(extension)) {
    throw new Error(
      `Unsupported artwork file "${fileName}". Use one of: ${[...supportedExtensions].join(", ")}.`
    );
  }

  const stem = path.basename(fileName, extension);
  const match = /^(?<title>[a-z0-9]+(?:[_-][a-z0-9]+)*)-(?<price>[1-9]\d*)(?<sold>-sold)?$/i.exec(
    stem
  );

  if (!match?.groups) {
    throw new Error(
      `Invalid artwork file "${fileName}". Use title_words-amount[-sold]${extension}.`
    );
  }

  const rawTitle = match.groups.title;
  const words = rawTitle.split(/[_-]+/);

  return {
    id: rawTitle.toLowerCase().replace(/_/g, "-"),
    name: words
      .map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1).toLowerCase()}`)
      .join(" "),
    price: Number(match.groups.price),
    image: `/artworks/${fileName}`,
    available: !match.groups.sold,
  };
}

export function renderArtworksFile(artworks) {
  const entries = artworks
    .map(
      (artwork) => `  {
    id: ${JSON.stringify(artwork.id)},
    name: ${JSON.stringify(artwork.name)},
    price: ${artwork.price},
    image: ${JSON.stringify(artwork.image)},
    available: ${artwork.available},
  },`
    )
    .join("\n");

  return `// This file is generated by scripts/generate-artworks.mjs. Do not edit it directly.\n\nexport type Artwork = {\n  id: string;\n  name: string;\n  price: number; // in INR\n  image: string; // path under /public/artworks\n  available: boolean; // false = sold\n};\n\nexport const artworks: Artwork[] = [\n${entries}\n];\n`;
}

export async function generateArtworks({
  sourceDirectory = artworksDirectory,
  destinationFile = outputFile,
} = {}) {
  const directoryEntries = await readdir(sourceDirectory, { withFileTypes: true });
  const files = directoryEntries.filter((entry) => entry.isFile()).map((entry) => entry.name);
  const artworks = files.map(parseArtworkFilename);
  const duplicateIds = artworks.filter(
    (artwork, index) => artworks.findIndex(({ id }) => id === artwork.id) !== index
  );

  if (duplicateIds.length > 0) {
    const ids = [...new Set(duplicateIds.map(({ id }) => id))].join(", ");
    throw new Error(`Duplicate artwork ID(s): ${ids}. Use unique artwork titles.`);
  }

  artworks.sort((first, second) => first.name.localeCompare(second.name));
  const contents = renderArtworksFile(artworks);

  let currentContents = "";
  try {
    currentContents = await readFile(destinationFile, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (contents !== currentContents) {
    await writeFile(destinationFile, contents, "utf8");
    console.log(`Generated ${path.relative(projectRoot, destinationFile)} from ${files.length} artwork file(s).`);
  }

  return artworks;
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  generateArtworks().catch((error) => {
    console.error(`Artwork catalogue generation failed: ${error.message}`);
    process.exitCode = 1;
  });
}
